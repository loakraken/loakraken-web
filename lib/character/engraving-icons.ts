/** The engraving's icon path, or null when we have no icon for that name. */
export function engravingIcon(name: string | null | undefined): string | null {
  const key = name?.trim();
  if (!key || !Object.hasOwn(ENGRAVING_ICON_FILES, key)) return null;
  const file = ENGRAVING_ICON_FILES[key];
  return `/engravings/${file}?v=${ENGRAVING_ICON_HASH[file]}`;
}
