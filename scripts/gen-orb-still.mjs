// Writes components/landing/orb-still-data.ts: the character loading orb's still frame (#1632) as plain data,
// so no client computes it (codex #1633 P3: 204 dots × 2 themes of trig at module load). The frame is the one
// the orb draws under reduced motion (t = 0.6), from the package's own preset, frame and paint, painted through
// a context that only records. Each dot becomes a round-capped stroke a hair long, grouped by its light colour,
// dark colour and radius (colours rounded to 16 steps and alpha to 0.05, ≤ 8/255 off on dots 0.3–2px across).
//   node scripts/gen-orb-still.mjs          write the file
//   node scripts/gen-orb-still.mjs --check  fail if the file is not what the installed package draws
//                                            (a package upgrade that changes the frame; the unit test runs this)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { MODE_FRAMES, paintFrame, resolvePreset } from "thinking-orbs/engine";
// The same colours the live orb uses (codex #1647 P3: one constant, so a tint change reaches the still too).
import { ORB_COLORS } from "../components/landing/orb-colors.ts";

const OUT = fileURLToPath(new URL("../components/landing/orb-still-data.ts", import.meta.url));
const SIZE = 64;
const STILL_T = 0.6;
const rgb = (hex) => {
  const n = Number.parseInt(hex.slice(1), 16);
  return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255 };
};
const TINT = { light: rgb(ORB_COLORS.light), dark: rgb(ORB_COLORS.dark) };
const version = createRequire(import.meta.url)("thinking-orbs/package.json").version;

function record(dark) {
  const { mode, opts } = resolvePreset("searching", SIZE);
  const frame = MODE_FRAMES[mode](SIZE, STILL_T, opts);
  if (frame.lines?.length) throw new Error(`the searching orb now draws ${frame.lines.length} lines; the still has no lines`);
  const dots = [];
  let fill = "";
  let at = { x: 0, y: 0, r: 0 };
  const ctx = {
    set fillStyle(value) {
      fill = value;
    },
    set strokeStyle(_) {},
    set lineWidth(_) {},
    beginPath() {},
    arc(x, y, r) {
      at = { x, y, r };
    },
    fill() {
      dots.push({ ...at, fill });
    },
    moveTo() {},
    lineTo() {},
    stroke() {},
  };
  paintFrame(ctx, frame, dark, dark ? TINT.dark : TINT.light);
  return dots;
}

const round = (rgba) => {
  const [r, g, b, a] = (rgba.match(/[\d.]+/g) ?? []).map(Number);
  const c = (v) => Math.min(255, Math.round(v / 16) * 16);
  return `rgba(${c(r)},${c(g)},${c(b)},${Math.round(a * 20) / 20})`;
};

const light = record(false);
const dark = record(true);
// One set of positions serves both themes: the recordings must be the same dots in the same order.
if (light.length !== dark.length || light.some((d, i) => d.x !== dark[i].x || d.y !== dark[i].y || d.r !== dark[i].r))
  throw new Error(`light (${light.length}) and dark (${dark.length}) recordings differ; the still needs one set of dots`);

const groups = new Map();
light.forEach((dot, i) => {
  const width = (dot.r * 2).toFixed(1);
  const key = `${round(dot.fill)}|${round(dark[i].fill)}|${width}`;
  const group = groups.get(key) ?? { light: round(dot.fill), dark: round(dark[i].fill), width: Number(width), dots: [] };
  group.dots.push(`M${dot.x.toFixed(1)} ${dot.y.toFixed(1)}h.01`);
  groups.set(key, group);
});

const body = [...groups.values()]
  .map((g) => `  { light: "${g.light}", dark: "${g.dark}", width: ${g.width}, d: "${g.dots.join("")}" },`)
  .join("\n");
const text = `// Generated by scripts/gen-orb-still.mjs from thinking-orbs ${version} — do not edit; run the script.
// The searching orb's still frame (t = ${STILL_T}, ${SIZE}px): ${light.length} dots in ${groups.size} groups.
export const ORB_STILL_SIZE = ${SIZE};
export const ORB_STILL: readonly { light: string; dark: string; width: number; d: string }[] = [
${body}
];
`;

if (process.argv.includes("--check")) {
  const now = readFileSync(OUT, "utf8").replace(/\r\n/g, "\n");
  if (now !== text) {
    console.error("orb-still-data.ts is out of date (thinking-orbs or ORB_COLORS changed): run node scripts/gen-orb-still.mjs");
    process.exit(1);
  }
  console.log(`orb-still-data.ts matches thinking-orbs ${version} (${light.length} dots, ${groups.size} groups)`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}: ${light.length} dots, ${groups.size} groups`);
}
